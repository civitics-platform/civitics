/**
 * Split a 30-minute row into two 15-minute rows, the first half taking the
 * ceiling of each count. The split is EVEN on purpose: the 30-minute series
 * cannot say where inside a half hour the 52x started, so an even split is the
 * reading that assumes nothing. Its one consequence worth knowing: the 16:00
 * half hour (221 req, 74 x 52x, 33 %) splits into two GREEN quarters, so the
 * first RED quarter is 16:30. Had all 74 landed in 16:15-16:30 (67 %), DOWN
 * would come one tick earlier.
 */
export function halfHourToQuarters(rows: FrontDoorRow[]): FrontDoorRow[] {
  const out: FrontDoorRow[] = [];
  for (const [startMs, req, n5xx, n52x] of rows) {
    const up = (n: number) => Math.ceil(n / 2);
    out.push([startMs, up(req), up(n5xx), up(n52x)]);
    out.push([startMs + 15 * 60 * 1000, req - up(req), n5xx - up(n5xx), n52x - up(n52x)]);
  }
  return out;
}

